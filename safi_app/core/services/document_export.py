def _md_to_pdf(text: str, title: str, attribution: Optional[str]) -> bytes:
    import html as _html
    import markdown as _markdown
    from xhtml2pdf import pisa

    body = _markdown.markdown(
        text,
        extensions=["extra", "sane_lists", "nl2br"],
        output_format="html5",
    )
    title_html = f'<div class="doc-title">{_html.escape(title)}</div>' if title else ""
    footer_html = f'<div class="doc-footer">{_html.escape(_footer_text(attribution))}</div>'
    doc = (
        f"<!DOCTYPE html><html><head><meta charset='utf-8'>"
        f"<style>{_PDF_CSS}</style></head><body>"
        f"{title_html}{body}{footer_html}"
        f"</body></html>"
    )
    out = io.BytesIO()
    result = pisa.CreatePDF(src=doc, dest=out, encoding="utf-8")
    if result.err:
        raise RuntimeError("PDF rendering failed")
    return out.getvalue()


def _md_to_xlsx(text: str, attribution: Optional[str]) -> bytes:
    import openpyxl
    from openpyxl.styles import Font
    from openpyxl.utils import get_column_letter

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Answer"
    ws.freeze_panes = "A2"

    header_font = Font(bold=True)
    row = 1

    def emit(cells):
        nonlocal row
        for col, val in enumerate(cells, start=1):
            ws.cell(row=row, column=col, value="".join(str(val)))
        row += 1

    csv_rows = list(csv.reader(io.StringIO(text)))
    if csv_rows and csv_rows[0] == ["Name", "Title", "URL", "Reachout"]:
        for col, cell_text in enumerate(csv_rows[0], start=1):
            ws.cell(row=row, column=col, value=cell_text).font = header_font
        row += 1
        for cells in csv_rows[1:]:
            if not any(cells):
                continue
            cells = (cells + [""] * 4)[:4]
            for col, cell_text in enumerate(cells, start=1):
                cell = ws.cell(row=row, column=col, value=cell_text)
                if col == 3 and re.match(r"^https://www\.linkedin\.com/in/[^\s]+$", cell_text):
                    cell.hyperlink = cell_text
                    cell.font = Font(color="0563C1", underline="single")
            row += 1
        emit([_footer_text(attribution)])
        for col in range(1, ws.max_column + 1):
            widths = [len(str(ws.cell(row=r, column=col).value or "")) for r in range(1, ws.max_row + 1)]
            ws.column_dimensions[get_column_letter(col)].width = min(max(widths, default=0) + 2, 60)
        buf = io.BytesIO()
        wb.save(buf)
        return buf.getvalue()

    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    i = 0
    n = len(lines)

    while i < n:
        line = lines[i]
        if "|" in line and i + 1 < n and _TABLE_SEP_RE.match(lines[i + 1]):
            header = _split_row(line)
            i += 2
            rows = []
            while i < n and "|" in lines[i] and lines[i].strip():
                rows.append(_split_row(lines[i]))
                i += 1
            for col, cell_text in enumerate(header, start=1):
                ws.cell(row=row, column=col, value=cell_text).font = header_font
            row += 1
            for r in rows:
                emit(r)
            row += 1
            continue
        stripped = line.strip()
        if not stripped:
            i += 1
            continue
        emit([stripped])
        i += 1

    emit([_footer_text(attribution)])

    widths = {}
    for col in range(1, ws.max_column + 1):
        widths[col] = min(max(
            (len(str(ws.cell(row=r, column=col).value or "")) for r in range(1, ws.max_row + 1)),
            default=0) + 2, 60)
        ws.column_dimensions[get_column_letter(col)].width = widths[col]

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def render(text: str, title: str, fmt: str,
           attribution: Optional[str] = None) -> Tuple[bytes, str, str]:
    if not text or not text.strip():
        raise ValueError("Nothing to export.")
    if len(text) > MAX_EXPORT_CHARS:
        raise ValueError("Answer is too long to export.")
    fmt = (fmt or "").lower()
    title = (title or "").strip()

    if fmt == "docx":
        return (
            _md_to_docx(text, title, attribution),
            "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            "docx",
        )
    if fmt == "pdf":
        return (_md_to_pdf(text, title, attribution), "application/pdf", "pdf")
    if fmt in ("xlsx", "excel"):
        return (
            _md_to_xlsx(text, attribution),
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            "xlsx",
        )
    if fmt in ("md", "markdown"):
        body = text if text.endswith("\n") else text + "\n"
        out = f"{body}\n---\n\n_{_footer_text(attribution)}_\n"
        return (out.encode("utf-8"), "text/markdown", "md")
    raise ValueError(f"Unsupported format '{fmt}'.")
